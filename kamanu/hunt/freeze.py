"""The freeze (H15): every row's hunt re-run from a clean state on its pinned engine.

    rebuild(root, engines, scopes=None) -> dict
        root     a directory: its profiles/rows/*.json are the rows (H4's format);
                 evidence/freeze/ and site/ are written under it, nothing else is.
        engines  engines(about, policy_text) -> a fresh engine (H1's interface), where `about`
                 is the row's "engine" object (its pin) and policy_text the row's policy.text.
                 It raises when the pinned engine cannot be had; the engine may also raise
                 during the hunt (it went away).
        scopes   R14d: scopes(engine) -> the path of the scope file (kamanu.hunt.scope) for an engine
                 the rebuild is about to hunt; it is forwarded to hunt_row as scope=. With no scopes,
                 or a scope that does not cover an engine's target, that engine's hunt is refused
                 before its first request: rebuild raises ScopeRefused and has written nothing (every
                 hunt runs before any write). The bundled in-process engines need none.

        For each row file, in name order: one fresh engine from engines(row's engine, row's
        policy text), never shared with another row, and the row's hunt on it
        (kamanu.hunt.row.hunt_row). The row file is then written again, in place:
          - re-run: the re-run's row (its date, sessions, profile and cells; the old row's
            engine object and any extra keys of the old row the re-run does not write, such as
            an adapter's facts), in which every cell whose verdict differs from the old row's
            is withdrawn;
          - no re-run (the engine could not be had, or went away during the hunt): the old row,
            in which every tested cell is withdrawn (its new verdict is "untested").
        A withdrawn cell is never kept by hand:
            {"verdict": "untested", "reason": ..., "diff": {"old": OLD, "new": NEW,
             "old_cell": the old cell, "new_cell": the re-run's cell or null}, "version", "date"}
        with the version and date of the row it is in. A cell whose verdict is unchanged is the
        re-run's cell (its session and trace are the re-run's).
        Then evidence/freeze/<YYYY-MM-DD>.json (the rebuild's UTC start date):
            {"date": ..., "finished": ..., "rows": {"<file>": {"engine": ..., "rerun": bool,
             "error": str | null, "cells": {"<test>": {"old": OLD, "new": NEW}}}},
             "reproduced": n, "withdrawn": n}
        with NEW the re-run's verdict before any withdrawal ("untested" with no re-run), and
        site/ regenerated by H10's generator (kamanu.hunt.matrix) from the rebuilt rows.

    python -m kamanu.hunt.freeze --rebuild [--engines MODULE:NAME] [--scopes MODULE:NAME]
        the same with root the working directory. `engines` is MODULE's attribute NAME when
        given, live_engines (below) otherwise; `scopes` is MODULE's attribute NAME. Exits 0 once
        the rows, the record and the page are written, whatever was withdrawn; 2 on a usage error;
        kamanu.hunt.scope.SCOPE_REFUSED_EXIT (6), nothing written, when a hunt was refused.

    live_engines(about, policy_text)
        the adapters of the pinned engines that this machine can reach, each checked against
        its pin before it is used:
          dogwood               DOGWOOD_BIN, whose SHA-256 must be the pin's binary-sha256 and
                                whose --version the pin's version (H4's adapter)
          redis-sliding-log,    REDIS_ADDR, a Redis whose INFO version is the row's
          python-limits         redis.version (H8's adapters, at the row's limiter settings)
        Any other engine (Kong, LiteLLM, AgentCore, the Dogwood Local Engine's harness) needs
        its own launcher, so it "cannot be had" here: LookupError, and its tested cells are
        withdrawn. Run their own gates' live runs instead.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from kamanu.hunt import matrix as M
from kamanu.hunt import row as R

TESTS = tuple(R.TESTS)
TESTED = ("fails", "passes")
ROWS_DIR = Path("profiles") / "rows"
FREEZE_DIR = Path("evidence") / "freeze"
DATE = "%Y-%m-%dT%H:%M:%SZ"


def _utc(t: float) -> str:
    return time.strftime(DATE, time.gmtime(int(t)))


def _verdict(row: dict | None, test: str) -> str:
    if row is None:
        return "untested"
    v = row.get("cells", {}).get(test, {}).get("verdict")
    return v if v in ("fails", "passes", "untested") else "untested"


def _close(engine) -> None:
    close = getattr(engine, "close", None)
    if callable(close):
        try:
            close()
        except Exception:  # noqa: BLE001 - closing a lost engine may fail; the hunt is over
            pass


def _rerun(engines, old: dict, scopes=None) -> tuple[dict | None, str | None]:
    """(the re-run's row, None) or (None, why there is none). ScopeRefused is not caught: a hunt with
    no scope for its target is not an engine that went away."""
    from kamanu.hunt import scope as SCOPE
    about = copy.deepcopy(old["engine"])
    text = old["policy"]["text"]
    try:
        engine = engines(copy.deepcopy(about), text)
    except Exception as e:  # noqa: BLE001 - any failure to obtain the pin is "cannot be had"
        return None, f"the pinned engine could not be had: {type(e).__name__}: {e}"
    try:
        grant = SCOPE.admit(engine, scopes(engine) if scopes is not None and SCOPE.in_process(engine) is None
                            else None)
    except SCOPE.ScopeRefused:
        _close(engine)
        raise
    try:
        return R.hunt_row(engine, text, about, scope=grant), None
    except Exception as e:  # noqa: BLE001 - the engine went away (or broke) during the hunt
        return None, f"the engine went away during the hunt: {type(e).__name__}: {e}"
    finally:
        _close(engine)


def _withdrawn(old_cell, new_cell, old_v: str, new_v: str, why: str, version: str, date: str,
               frozen: str) -> dict:
    return {"verdict": "untested",
            "reason": f"withdrawn by the freeze of {frozen[:10]}: {why}; the cell was {old_v!r}, "
                      f"the re-run gives {new_v!r}",
            "diff": {"old": old_v, "new": new_v, "old_cell": copy.deepcopy(old_cell),
                     "new_cell": copy.deepcopy(new_cell)},
            "version": version, "date": date}


def rebuild_row(old: dict, new: dict | None, error: str | None, record: str, frozen: str) -> tuple[dict, dict]:
    """(the row to write, {test: {"old", "new"}})."""
    cells = {t: {"old": _verdict(old, t), "new": _verdict(new, t)} for t in TESTS}
    if new is not None:
        out = copy.deepcopy(new)
        out["engine"] = copy.deepcopy(old["engine"])
        for k, v in old.items():
            if k not in out:
                out[k] = copy.deepcopy(v)               # an adapter's facts the hunt does not write
        why = "the re-run on the pinned engine gives another verdict"
    else:
        out = copy.deepcopy(old)
        why = error or "no re-run"
    version, date = out["engine"]["version"], out["date"]
    for t in TESTS:
        o, n = cells[t]["old"], cells[t]["new"]
        if o != n:
            out["cells"][t] = _withdrawn(old["cells"].get(t), None if new is None else new["cells"].get(t),
                                         o, n, why, version, date, frozen)
        elif new is None:
            out["cells"][t] = copy.deepcopy(old["cells"][t])
    out["freeze"] = {"record": record, "date": frozen, "rerun": new is not None,
                     "previous_date": old.get("date")}
    if error:
        out["freeze"]["error"] = error
    return out, cells


def _dump(row: dict) -> str:
    return json.dumps(row, indent=1, ensure_ascii=False) + "\n"


def rebuild(root, engines, scopes=None) -> dict:
    root = Path(root)
    t0 = time.time()
    day = time.strftime("%Y-%m-%d", time.gmtime(t0))
    record_rel = (FREEZE_DIR / f"{day}.json").as_posix()
    files = sorted((root / ROWS_DIR).glob("*.json"))
    olds = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in files}
    reruns = {}
    for name, old in olds.items():                       # every hunt first, then every write
        reruns[name] = _rerun(engines, old, scopes)
    rows, out_rows = {}, {}
    counts = {"reproduced": 0, "withdrawn": 0}
    for name, old in olds.items():
        new, error = reruns[name]
        rebuilt, cells = rebuild_row(old, new, error, record_rel, _utc(t0))
        out_rows[name] = rebuilt
        rows[name] = {"engine": copy.deepcopy(old["engine"]), "rerun": new is not None, "error": error,
                      "old_date": old.get("date"), "new_date": None if new is None else new["date"],
                      "cells": cells}
        for c in cells.values():
            counts["reproduced" if c["old"] == c["new"] else "withdrawn"] += 1
    for name, row in out_rows.items():
        (root / ROWS_DIR / name).write_text(_dump(row), encoding="utf-8")
    t1 = time.time()
    rec = {"date": _utc(t0), "finished": _utc(t1), "rows": rows, **counts}
    (root / FREEZE_DIR).mkdir(parents=True, exist_ok=True)
    (root / record_rel).write_text(json.dumps(rec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    M.build(root, root / "site")
    return rec


# ---------------------------------------------------------------- the live engines
def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _dogwood(about: dict, policy_text: str):
    from kamanu import examples
    from kamanu.hunt.dogwood import DogwoodEngine, binary
    b = binary()
    ob = about.get("obtained", {})
    if ob.get("kind") != "binary-sha256" or _sha256(b) != ob.get("value"):
        raise LookupError(f"DOGWOOD_BIN={b} is not the pinned binary (sha256 {ob.get('value')})")
    v = subprocess.run([b, "--version"], capture_output=True, text=True, timeout=60).stdout.strip()
    if v != about.get("version"):
        raise LookupError(f"DOGWOOD_BIN --version is {v!r}, the pin is {about.get('version')!r}")
    pol = R.read_policy(policy_text, "amount")
    tmp = Path(tempfile.mkdtemp(prefix="kamanu-freeze-"))
    (tmp / "policy.dw").write_text(policy_text, encoding="utf-8")
    _, example = examples.files("dogwood")             # the Pay action's schema, in the policy's namespace
    text = re.sub(r"namespace\s+\w+", f"namespace {pol['namespace']}", example.read_text(encoding="utf-8"), count=1)
    (tmp / "schema.cedarschema").write_text(text, encoding="utf-8")
    return DogwoodEngine(b, tmp / "policy.dw", tmp / "schema.cedarschema", pol["namespace"], pol["action"])


def _redis(module: str, row: dict):
    addr = os.environ.get("REDIS_ADDR")
    if not addr:
        raise LookupError("REDIS_ADDR is not set")
    from kamanu.hunt.adapters import redis_common as RC
    want = (row.get("redis") or {}).get("version")
    c = RC.Client(addr)
    try:
        info = c.call("INFO", "server")
    finally:
        c.close()
    text = info.decode("utf-8", "replace") if isinstance(info, bytes) else str(info)
    have = next((ln.split(":", 1)[1].strip() for ln in text.splitlines() if ln.startswith("redis_version:")), None)
    if not want or have != want:
        raise LookupError(f"the Redis at REDIS_ADDR is {have!r}, the row is pinned to {want!r}")
    lim = row.get("limiter") or {}
    mod = importlib.import_module(f"kamanu.hunt.adapters.{module}")
    return mod.engine(addr, int(lim["cap"]), int(lim["window_s"]))


def live_engines(about, policy_text, row: dict | None = None):
    name = (about or {}).get("name")
    if name == "dogwood":
        return _dogwood(about, policy_text)
    if name in ("redis-sliding-log", "python-limits"):
        if row is None:
            raise LookupError(f"{name}: the row's limiter settings are needed")
        return _redis("redis_sliding_log" if name == "redis-sliding-log" else "redis_python_limits", row)
    raise LookupError(f"no launcher for the pinned engine {name!r} in this command (its own gate's live run "
                      f"re-records it)")


class _RowEngines:
    """live_engines with each row's own extra facts (Redis version, limiter settings)."""

    def __init__(self, root: Path):
        self.by = {}
        for p in sorted((root / ROWS_DIR).glob("*.json")):
            try:
                r = json.loads(p.read_text(encoding="utf-8"))
                self.by[json.dumps([r["engine"], r["policy"]["text"]], sort_keys=True)] = r
            except (OSError, ValueError, KeyError, TypeError):
                pass

    def __call__(self, about, policy_text):
        row = self.by.get(json.dumps([about, policy_text], sort_keys=True))
        return live_engines(about, policy_text, row)


def load_engines(spec: str, option: str = "--engines"):
    mod, _, attr = spec.partition(":")
    if not mod or not attr:
        raise ValueError(f"{option} {spec!r} is not MODULE:NAME")
    fn = getattr(importlib.import_module(mod), attr)
    if not callable(fn):
        raise ValueError(f"{option} {spec!r} is not callable")
    return fn


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m kamanu.hunt.freeze")
    ap.add_argument("--rebuild", action="store_true", required=True,
                    help="re-run every row's hunt on its pinned engine and pin the numbers")
    ap.add_argument("--engines", help="MODULE:NAME, engines(about, policy_text) -> a fresh engine")
    ap.add_argument("--scopes", help="MODULE:NAME, scopes(engine) -> the path of the scope file that covers the "
                                     "engine about to be hunted (R14d); without it a hunt of anything but a "
                                     "bundled in-process engine is refused and nothing is written")
    try:
        a = ap.parse_args(argv)
    except SystemExit:
        return 2
    root = Path.cwd()
    try:
        engines = load_engines(a.engines) if a.engines else _RowEngines(root)
        scopes = load_engines(a.scopes, "--scopes") if a.scopes else None
    except (ImportError, AttributeError, ValueError) as e:
        print(f"kamanu matrix --rebuild: {e}", file=sys.stderr)
        return 2
    from kamanu.hunt import scope as SCOPE
    try:
        rec = rebuild(root, engines, scopes)
    except SCOPE.ScopeRefused as e:
        print(f"kamanu matrix --rebuild: {e}; nothing was written (give --scopes MODULE:NAME)", file=sys.stderr)
        return SCOPE.SCOPE_REFUSED_EXIT
    day = rec["date"][:10]
    for name, r in rec["rows"].items():
        changed = [f"{t} {c['old']}->{c['new']}" for t, c in r["cells"].items() if c["old"] != c["new"]]
        state = "re-run" if r["rerun"] else f"no re-run ({r['error']})"
        print(f"{name}: {state}; " + (f"withdrawn: {', '.join(changed)}" if changed else "every cell reproduced"))
    print(f"wrote evidence/freeze/{day}.json: {rec['reproduced']} cells reproduced, {rec['withdrawn']} withdrawn; "
          f"site/ regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
